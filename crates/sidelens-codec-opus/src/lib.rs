//! SideLens 的 Opus 编解码器封装
//!
//! # 为什么不用 `opus` / `opusic-sys`
//!
//! 那两个 crate 的 build.rs 会调 **cmake** 去编译 libopus 的 C 源码。
//! 本机（以及大多数只装了 VS Build Tools 的机器）没有独立的 cmake ——
//! VS 自带的那个在
//! `Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin`，
//! 默认不在 PATH 里。构建会失败在 `failed to execute command: program not found`，
//! 错误信息完全没提「你需要 cmake」。
//!
//! `audiopus` 走的是另一条路：它的 `audiopus_sys` crate 里**自带预编译的
//! `libopus.lib`**（`msvc/x64/` 与 `msvc/x86/` 各一份，2MB）。零外部工具链依赖。
//!
//! 实测对比：
//!
//! | crate | 需要 cmake | 从零编译耗时 |
//! | --- | --- | --- |
//! | `opus` + `opusic-sys` | ✅ 是 | 9.2 秒 |
//! | `audiopus` | ❌ 否 | 1.4 秒 |
//!
//! # 这一层解决什么问题
//!
//! `sidelens-codec::audio` 只管时间戳（PTS 产生与消费），**不含编码器**。
//! 本 crate 补上真实编解码，并且把「编码器引入的额外延迟」显式暴露出来 ——
//! 那是音画同步里最容易被忽略的一项。
//!
//! ## 编码器 lookahead：6.5ms 的隐形偏移
//!
//! Opus 编码器内部有 **312 采样（48kHz 下 6.50ms）的 lookahead**。
//! 这意味着：喂进去的第 0 个采样，会出现在**解码输出**的第 312 个位置。
//!
//! 后果：
//!
//! ```text
//! 音频 PTS 说「这段声音是 t 时刻的」
//! 但实际发声时刻是 t + 6.50ms
//! AvSync 以音频 PTS 为主时钟 → 视频按 t 对齐 → 视频比声音早 6.5ms
//! ```
//!
//! 6.5ms 小于人眼可察觉的音画不同步阈值（约 40ms），暂时不致命。
//! 但它**必须被记录下来**，因为：
//!
//! 1. 将来换成 60ms 帧长时 lookahead 会变（实测：**不变**，见下）
//! 2. 这个偏移会与其他延迟叠加（采集缓冲、抖动缓冲、渲染）
//! 3. 不做补偿时，它是**单向**的 —— 不会自我抵消
//!
//! # 实测：lookahead 与帧长无关
//!
//! 原文档假设「换成 60ms 帧长时 lookahead 会变」。实测 2.5 / 20 / 40 / 60ms
//! 四档都是 **312 采样 = 6500µs**，一档不差。它是解码器侧 CELT 的固定
//! 重叠窗，与编码帧长无关。
//!
//! # 实测数据（48kHz 单声道 20ms 帧，32kbps，Voip）
//!
//! | 输入 | 每帧字节 | 说明 |
//! | --- | --- | --- |
//! | 静音 | 35 | 不是 0；仍要发最小帧维持解码器状态 |
//! | 440Hz 正弦 | 82 | |
//! | 白噪声 | 81 | Voip 模式的噪声抑制 |
//! | 类语音 | 83 | |
//!
//! 编码后相对原 PCM（1920 字节/帧）的压缩比约 **23x**。
//!
//! # DTX / in-band FEC / 帧长：三个可测的结论
//!
//! 见 [`encoder::OpusEncoder::set_dtx`]、[`encoder::OpusEncoder::set_inband_fec`]
//! 与 [`packet`] 的文档。完整实测在 `tests/tuning.rs`（33 项）。
//!
//! ## 1. DTX：线上收益只有 1.9x，不是 ∞
//!
//! 静音 5 秒（48kHz 单声道 20ms 32kbps Voip）：
//!
//! | 指标 | 无 DTX | 有 DTX | 比值 |
//! | --- | --- | --- | --- |
//! | 载荷字节 | 8746 | 960 | **9.1x** |
//! | 线上码率（含 32B 帧头） | 26.8 kbps | 14.3 kbps | **1.9x** |
//!
//! 差距全在帧头：1 字节的 DTX 包配 32 字节的协议帧头，放大 32 倍。
//! 静音期帧头占总字节 **89.3%**。要拿到 DTX 的全部收益，必须让协议层
//! 支持「空帧不发」—— 那是 `sidelens-proto` 的改动，不在本 crate。
//!
//! DTX 还有两个硬约束：
//!
//! - 前 **10 帧**不抑制（VAD 预热），之后每 **21 帧**强制发一帧真实的
//!   （`MAX_CONSECUTIVE_DTX`），所以静音期不是零带宽
//! - **语音段一帧都不省**：连续语音下 `dtx_frames == 0`，字节数完全不变
//!
//! ## 2. in-band FEC：不增加码流，但有两条硬边界
//!
//! **不增加码流**（SILK 的 LBRR 是从语音帧内部挪比特，不是额外加）：
//!
//! | 配置 | 250 帧总字节 | 相对无 FEC |
//! | --- | --- | --- |
//! | 无 FEC | 20755 | 1.000 |
//! | FEC loss=0 | 20755 | 1.000（不生效） |
//! | FEC loss=10 | 20487 | 0.987 |
//! | FEC loss=30 | 20531 | 0.989 |
//!
//! 代价是**正常解码的音质下降**：RMSE 1741 → 2154（loss=30，+23.7%）。
//! 没有丢包时那部分比特就白费了。
//!
//! **边界一：码率 < 16 kbps 时完全无效。** 逐 500bps 扫描实测：
//! 6/8/10/12/14/15.5 kbps 下 FEC 输出与 PLC 输出**逐采样相同**（无 LBRR），
//! 16.0 kbps 起才生效。
//!
//! **边界二：纯 CELT 模式下完全无效。** LBRR 只存在于 SILK / Hybrid。
//! `Application::LowDelay` 或高码率音乐会走纯 CELT，此时开 FEC 是空操作
//! （实测 0/6 修复）。默认 Voip + 32kbps 走 SILK/Hybrid，安全。
//!
//! **边界三：事后修复。** 第 N 帧丢、第 N+1 帧到达才能修。实测抖动缓冲
//! `target_ms` ≤ 40ms（容量 3 帧）时第 N 帧**已经播出去了**，修好也没用；
//! 只有 ≥ 60ms 才有意义。当前 daemon 用 40ms —— 刚好卡在临界点上。
//!
//! 深度够时的净收益：默认配置下 FEC 胜 13/16，平均 RMSE 702 vs PLC 2221（**3.16x**）。
//!
//! ## 3. 帧长：40/60ms 不是新模式，是打包
//!
//! 用 [`packet::toc`] 解析包结构实测（32kbps Voip 语音）：
//!
//! | 请求帧长 | TOC | config | code | 内部帧数 | 内部帧长 |
//! | --- | --- | --- | --- | --- | --- |
//! | 20ms | 0x78 | 15 | 0 | 1 | 20ms |
//! | 40ms | 0x7A | 15 | 2 | 2 | 20ms |
//! | 60ms | 0xDB | 27 | 3 | 3 | 20ms |
//!
//! libopus 把 2 / 3 个 20ms 帧打进一个包，**内部帧长仍是 20ms**。
//! 这解释了两件事：
//!
//! 1. **lookahead 恒为 312 采样**（6500µs），2.5/20/40/60ms 四档一档不差。
//!    原文档假设「换 60ms 帧长时 lookahead 会变」—— 实测不变，
//!    所以加大帧长不改善也不恶化音画同步。
//! 2. **丢一个 60ms 包 = 丢 3 个内部帧**，PLC 要连续外推 3 次。
//!
//! 帧头开销（5 秒类语音，含 32B 协议帧头）：
//!
//! | 帧长 | 包数 | 载荷码率 | 帧头占比 | 线上码率 |
//! | --- | --- | --- | --- | --- |
//! | 20ms | 250 | 33.2 kbps | **27.8%** | 46.0 kbps |
//! | 40ms | 125 | 33.3 kbps | 16.1% | 39.7 kbps |
//! | 60ms | 83 | 33.6 kbps | **11.3%** | 37.9 kbps |
//!
//! 载荷码率三档几乎相同（Opus 按「每秒多少比特」算，与帧长无关）——
//! **省下来的全是帧头**。

