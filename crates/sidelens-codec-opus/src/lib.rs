/// Opus 允许的帧长档位（毫秒）
///
/// # 为什么必须固定这几档
///
/// 传入 15ms 这类「看起来合理」的值，编码器**不会报错**，而是静默地
/// 编成 10ms 或 20ms —— 于是 `frame_duration_us()` 算出来的时长与实际
/// 码流不符，音画同步慢慢漂移。
pub const ALLOWED_FRAME_MS: [f64; 6] = [2.5, 5.0, 10.0, 20.0, 40.0, 60.0];

/// 判断帧长是否合法
pub fn is_allowed_frame_ms(ms: f64) -> bool {
    ALLOWED_FRAME_MS
        .iter()
        .any(|a| (a - ms).abs() < f64::EPSILON * 8.0)
}
